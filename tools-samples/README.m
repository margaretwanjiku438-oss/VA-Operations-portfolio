## 📋 Trello: Client Onboarding & Weekly Operations

A sample Trello board showing how I manage client onboarding and weekly operations.

**How it works**
- Work moves left to right: Requests → This Week → In Progress → Waiting on Client → Review → Done
- Every card has an owner, a due date and a colour-coded label (Admin, CRM, Onboarding, Social Media, Travel & Bookings)
- Cards that need several steps use checklists, such as the onboarding card (2 of 5 steps complete)
- A "How the board works" card explains the process to anyone joining the board

**What it shows**
- Task tracking and deadline management
- Follow-up tracking, using the Waiting on Client list
- Clear visibility for clients and leadership
- A repeatable setup I can apply to a new client in the first week

